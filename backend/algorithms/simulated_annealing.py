import numpy as np
import math
import random
from typing import Optional


# Re-use the same objective function definition as hill_climbing.py
def _objective_function(x: float, func_type: str = "multimodal") -> float:
    """
    'multimodal' : x·sin(x) + x·cos(2x)
    'quadratic'  : -(x-3)² + 9
    """
    if func_type == "quadratic":
        return -(x - 3.0) ** 2 + 9.0
    return x * math.sin(x) + x * math.cos(2.0 * x)


def simulated_annealing(
    initial_x: float,
    initial_temp: float = 1000.0,
    cooling_rate: float = 0.995,
    max_iterations: int = 1000,
    func_type: str = "multimodal",
    seed: Optional[int] = None,
) -> dict:
    """
    Simulated Annealing for 1-D maximisation.

    At each step a neighbour is generated by adding Gaussian noise scaled
    by the current temperature.  If the neighbour is better it is always
    accepted; if it is worse it is accepted with the Boltzmann probability
        P = exp(Δ / T)
    where Δ = f(neighbour) − f(current) < 0.

    Temperature decreases geometrically: T_{k+1} = cooling_rate · T_k.

    Returns
    -------
    dict:
        best_x      : float
        best_value  : float
        history     : list[{iteration, x, value, temperature, accepted, acceptance_prob}]
        iterations  : int
        message     : str
        success     : bool
    """
    if seed is not None:
        random.seed(seed)

    if initial_temp <= 0:
        return _empty_result("initial_temp must be positive.")
    if not (0 < cooling_rate < 1):
        return _empty_result("cooling_rate must be in (0, 1).")
    if max_iterations <= 0:
        return _empty_result("max_iterations must be positive.")

    current_x     = float(initial_x)
    current_value = _objective_function(current_x, func_type)

    best_x     = current_x
    best_value = current_value
    temp       = float(initial_temp)

    history: list[dict] = []
    history.append({
        "iteration":      0,
        "x":              round(current_x, 6),
        "value":          round(current_value, 6),
        "temperature":    round(temp, 4),
        "accepted":       True,
        "acceptance_prob": 1.0,
    })

    for iteration in range(1, max_iterations + 1):
        # Neighbour generation: Gaussian perturbation, std proportional to temperature
        step = random.gauss(0, max(0.01, temp / initial_temp))
        neighbor_x     = current_x + step
        neighbor_value = _objective_function(neighbor_x, func_type)

        delta = neighbor_value - current_value

        if delta > 0:
            # Improvement – always accept
            acceptance_prob = 1.0
            accepted = True
        else:
            # Degradation – accept with Boltzmann probability
            if temp > 1e-10:
                acceptance_prob = math.exp(delta / temp)
            else:
                acceptance_prob = 0.0
            accepted = random.random() < acceptance_prob

        if accepted:
            current_x     = neighbor_x
            current_value = neighbor_value

        # Update global best (we maximise)
        if current_value > best_value:
            best_value = current_value
            best_x     = current_x

        history.append({
            "iteration":      iteration,
            "x":              round(current_x, 6),
            "value":          round(current_value, 6),
            "temperature":    round(temp, 4),
            "accepted":       accepted,
            "acceptance_prob": round(acceptance_prob, 6),
        })

        # Cool down
        temp *= cooling_rate

        # Early stop: temperature effectively zero
        if temp < 1e-10:
            break

    return {
        "best_x":     round(best_x, 6),
        "best_value": round(best_value, 6),
        "history":    history,
        "iterations": len(history) - 1,
        "message": (
            f"SA complete. Best x={round(best_x,6)}, "
            f"value={round(best_value,6)} after {len(history)-1} iteration(s)."
        ),
        "success": True,
    }


def _empty_result(message: str) -> dict:
    return {
        "best_x":     0.0,
        "best_value": 0.0,
        "history":    [],
        "iterations": 0,
        "message":    message,
        "success":    False,
    }
